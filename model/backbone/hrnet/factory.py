def _hrnet(arch: str, pretrained: bool = True, progress: bool = True, **kwargs):
    cfg = MODEL_CONFIGS[arch]
    model = HighResolutionNet(cfg, **kwargs)
    if pretrained:
        url = MODEL_URLS.get(arch, None)
        if url is None:
            logger.warning(f"No pretrained URL for {arch}; loading uninitialized weights.")
        else:
            state_dict = load_state_dict_from_url(url, progress=progress, map_location='cpu')
            model.load_state_dict(state_dict, strict=False)
    return model

def hrnet18(pretrained=True, progress=True, **kwargs):
    return _hrnet('hrnet18', pretrained, progress, **kwargs)

def hrnet32(pretrained=True, progress=True, **kwargs):
    return _hrnet('hrnet32', pretrained, progress, **kwargs)

def hrnet48(pretrained=True, progress=True, **kwargs):
    return _hrnet('hrnet48', pretrained, progress, **kwargs)
